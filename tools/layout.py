#!/usr/bin/env python3
"""Writes vst/layout.conf (and the panel artwork, via art.py) for Nova Editor: ONE page.
Top: rounded patch keys either side of a two-line display (category/genre or the last edit, then the patch name)
with a connection light; EDIT/PATCHES and ARP on the right. EDIT: five sections in two rows. PATCHES: the librarian.
Every knob one size, every key rounded; labels and titles baked in Inter, live values in MPC's own font."""
import json, os
import art
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {p["key"]: p["name"].upper() for p in json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]}

R = 38
E, P = "when=view:Edit", "when=view:Patches"
L = ["# Nova Editor (MiniNova editor/librarian) - generated by tools/layout.py, do not edit by hand",
     "art_css=skin.css",
     "theme_bg=24282e", "theme_panel=24282e", "theme_line=3a4048", "theme_ink=e9eef2", "theme_ink_dim=c3ccd5",
     "theme_ink_faint=8c96a1", "theme_accent=1a86c4", "theme_accent_hi=7fdcff", "theme_knob_face=1d2126",
     "theme_knob_ring=343a42", "theme_knob_dot=5fd0ff", "theme_lcd=0d171c", "theme_display_ink=8fe6ff",
     "theme_btn_text=ffffff", "theme_tile_on=17628f", "theme_seg_active=1a7fb8", "theme_seg_inactive=323840",
     "theme_seg_active_tx=ffffff", "knob_look=ledring",
     "[tab NOVA]"]
WELLS = []

def text(cx, cy, label, size=1.4, color="9fb0bf", align="center", weight=600, spacing=0, when=""):
    L.append('text cx=%d cy=%d label="%s" size=%.2f color=%s align=%s weight=%d spacing=%g fontfile=fonts/Inter.ttf %s'
             % (cx, cy, label, size, color, align, weight, spacing, when))

# ---- top band: patch keys, display, view and arp
LCD = (88, 94, 744, 112)                 # x, y, w, h (layout coordinates)
L.append('button cx=48 cy=150 w=64 h=112 label="" key=patch_prev img=art/key_prev.svg img_on=art/key_prev_on.svg')
L.append('button cx=872 cy=150 w=64 h=112 label="" key=patch_next img=art/key_next.svg img_on=art/key_next_on.svg')
L.append('readout cx=420 cy=122 w=620 h=30 label="" key=lcd_info box=0 tsize=19 tcolor=5fbfe6 talign=left')
L.append('readout cx=420 cy=170 w=620 h=58 label="" key=lcd_name box=0 tsize=44 tcolor=a6ecff talign=left')
L.append('picture x=772 y=110 w=40 h=24 key=linked files="art/led_off.svg,art/led_on.svg"')
text(792, 152, "MININOVA", 1.05, "5d7f90", weight=700, spacing=1.5)
L.append('enum_h cx=1090 cy=122 label="" key=view sw=170')
L.append('enum_h cx=1090 cy=180 label="" key=arp_on sw=170')

# ---- sections
ROWS_Y = [(222, 236), (470, 236)]
def section(x, w, row, title, keys, head=None):
    y, h = ROWS_Y[row]
    WELLS.append((x, y, w, h, "Edit"))
    text(x + 22, y + 26, title, 1.35, "8fa3b4", align="left", weight=700, spacing=3, when=E)
    for item in head or []:
        L.append(item % {"y": y + 26, "E": E})
    step = w / len(keys)
    cy = y + 124
    for i, k in enumerate(keys):
        cx = int(x + step * (i + 0.5))
        L.append('knob cx=%d cy=%d r=%d label="" ns=0 vy=36 key=%s %s' % (cx, cy, R, k, E))
        text(cx, cy + 56, NAMES[k], 1.2, "d6dee5", weight=600, spacing=0.5, when=E)

def seg(cx, key, sw):
    return 'enum_h cx=%d cy=%%(y)d label="" key=%s sw=%d %%(E)s' % (cx, key, sw)

def pop(cx, key, w, cols=None, cw=None):
    extra = (" cols=%d" % cols if cols else "") + (" cw=%d" % cw if cw else "")
    return 'popup cx=%d cy=%%(y)d w=%d h=38 label="" key=%s%s %%(E)s' % (cx, w, key, extra)

# row 1: OSC | FILTER
section(16, 650, 0, "OSC", ["o_semi", "o_cents", "o_pw", "o_dens", "o_level"],
        [seg(250, "osc_sel", 56), pop(520, "o_wave", 250, cols=8, cw=152)])
section(682, 582, 0, "FILTER", ["f_freq", "f_res", "f_env", "f_drive"], [pop(1120, "f_type", 220, cols=2, cw=120)])
# row 2: ENVELOPE | LFO | OUTPUT
section(16, 540, 1, "ENVELOPE", ["e_att", "e_dec", "e_sus", "e_rel"], [seg(354, "env_sel", 60)])
section(572, 400, 1, "LFO", ["l_rate", "l_delay", "l_slew"], [seg(724, "lfo_sel", 44), pop(888, "l_wave", 150, cols=5, cw=150)])
section(988, 276, 1, "OUTPUT", ["fx_mix", "glide"], [pop(1186, "audio_in", 140)])

# ---- PATCHES view
L.append('list x=16 y=222 w=832 h=484 key=row cols=2 rows=8 order=cols th=57 gap=4 tsize=22 tcolor=e9eef2 color=1d2228 talign=left %s' % P)
WELLS.append((864, 222, 400, 484, "Patches"))
text(886, 248, "LIBRARY", 1.35, "8fa3b4", align="left", weight=700, spacing=3, when=P)
L.append('enum_h cx=1064 cy=294 label="" key=lib_bank sw=76 %s' % P)   # five banks: A B C Imported Synth
L.append('button cx=916 cy=350 w=56 h=48 label="" key=lib_page_prev img=art/small_prev.svg img_on=art/small_prev_on.svg %s' % P)
L.append('readout cx=1064 cy=350 w=224 h=48 label="" key=lib_page tsize=21 tcolor=a6ecff talign=center %s' % P)
L.append('button cx=1212 cy=350 w=56 h=48 label="" key=lib_page_next img=art/small_next.svg img_on=art/small_next_on.svg %s' % P)
text(1064, 410, "WRITE TO", 1.2, "8fa3b4", weight=700, spacing=2, when=P)
L.append('enum_h cx=976 cy=440 label="" key=tgt_bank sw=52 %s' % P)
L.append('knob cx=1188 cy=440 r=30 label="" ns=0 vy=10 key=tgt_slot %s' % P)
text(1124, 440, "SLOT", 1.2, "8fa3b4", align="right", weight=700, spacing=2, when=P)
L.append('button cx=1064 cy=560 w=352 h=52 label="WRITE" key=write %s' % P)
L.append('button cx=972 cy=640 w=168 h=52 label="RECEIVE" key=receive %s' % P)
L.append('button cx=1156 cy=640 w=168 h=52 label="EXPORT" key=export %s' % P)

L.append('qlinks "NOVA" = o_semi,o_cents,o_pw,o_dens,f_freq,f_res,f_env,f_drive,e_att,e_dec,e_sus,e_rel,l_rate,l_delay,fx_mix,glide')

# ---- artwork: plate + display + wells (switching with the view) + keys + LED
adir = os.path.join(ROOT, "vst", "art")
os.makedirs(adir, exist_ok=True)
for f in os.listdir(adir):
    os.remove(os.path.join(adir, f))
art.write_plate(os.path.join(adir, "plate.svg"), LCD)
art.write_keys(adir)
wl = ["art file=art/plate.svg x=0 y=86 w=1280 h=628"]
for i, (x, y, w, h, view) in enumerate(WELLS):
    name = "art/well_%d.svg" % i
    art.write_well(os.path.join(ROOT, "vst", name), x, y, w, h)
    wl.append("art file=%s x=%d y=%d w=%d h=%d when=view:%s" % (name, x - art.M, y - art.M, w + 2 * art.M, h + 2 * art.M, view))
k = L.index("[tab NOVA]") + 1
L[k:k] = wl
open(os.path.join(ROOT, "vst", "layout.conf"), "w").write("\n".join(L) + "\n")
print("layout.conf: %d lines" % len(L))
